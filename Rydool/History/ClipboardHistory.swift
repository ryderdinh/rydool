import AppKit
import Combine
import ImageIO
import UniformTypeIdentifiers

@MainActor
final class ClipboardHistory: ObservableObject {
    #if DEBUG
    static let shared: ClipboardHistory = {
        let environment = ProcessInfo.processInfo.environment
        guard let path = environment["RYDOOL_TEST_DATA_DIR"],
              let boardName = environment["RYDOOL_TEST_PASTEBOARD"],
              let suiteName = environment["RYDOOL_TEST_DEFAULTS"],
              let defaults = UserDefaults(suiteName: suiteName) else { return ClipboardHistory() }
        return ClipboardHistory(pasteboard: NSPasteboard(name: NSPasteboard.Name(boardName)), defaults: defaults,
                                storeURL: URL(fileURLWithPath: path, isDirectory: true).appendingPathComponent("history.sqlite"))
    }()
    #else
    static let shared = ClipboardHistory()
    #endif
    @Published private(set) var items: [HistoryItem] = []
    @Published var errorMessage: String?
    @Published var tracking: Bool {
        didSet {
            defaults.set(tracking, forKey: "clipboardTracking")
            generation &+= 1
            // Discard the clipboard that existed during the paused period.
            lastChangeCount = pasteboard.changeCount
        }
    }
    @Published var maxItems: Int {
        didSet { maxItems = max(1, min(maxItems, 5000)); defaults.set(maxItems, forKey: "historyMaxItems"); applyLimits() }
    }
    @Published var maxMegabytes: Int {
        didSet { maxMegabytes = max(20, min(maxMegabytes, 5000)); defaults.set(maxMegabytes, forKey: "historyMaxMB"); applyLimits() }
    }
    @Published var excludedApps: String {
        didSet { defaults.set(excludedApps, forKey: "excludedBundleIDs"); generation &+= 1 }
    }
    private var excludedIDs: Set<String> {
        Set(excludedApplicationIDs)
    }
    var excludedApplicationIDs: [String] {
        var seen = Set<String>()
        return excludedApps.components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty && seen.insert($0).inserted }
    }

    func addExcludedApplications(_ urls: [URL]) -> Int {
        var ids = excludedApplicationIDs
        var paths = defaults.dictionary(forKey: "excludedApplicationPaths") as? [String: String] ?? [:]
        let previousPaths = paths
        var invalid = 0
        for url in urls {
            guard url.pathExtension.lowercased() == "app", let bundle = Bundle(url: url),
                  let id = bundle.bundleIdentifier, !id.isEmpty else {
                invalid += 1
                continue
            }
            if !ids.contains(id) { ids.append(id) }
            paths[id] = url.path
        }
        defaults.set(paths, forKey: "excludedApplicationPaths")
        let updated = ids.joined(separator: "\n")
        if updated != excludedApps { excludedApps = updated }
        else if paths != previousPaths { objectWillChange.send() }
        return invalid
    }

    func removeExcludedApplication(_ id: String) {
        excludedApps = excludedApplicationIDs.filter { $0 != id }.joined(separator: "\n")
        var paths = defaults.dictionary(forKey: "excludedApplicationPaths") as? [String: String] ?? [:]
        paths.removeValue(forKey: id)
        defaults.set(paths, forKey: "excludedApplicationPaths")
    }

    func excludedApplicationURL(_ id: String) -> URL? {
        if let path = (defaults.dictionary(forKey: "excludedApplicationPaths") as? [String: String])?[id],
           FileManager.default.fileExists(atPath: path),
           Bundle(url: URL(fileURLWithPath: path))?.bundleIdentifier == id {
            return URL(fileURLWithPath: path)
        }
        return NSWorkspace.shared.urlForApplication(withBundleIdentifier: id)
    }

    func excludedApplicationLastKnownName(_ id: String) -> String? {
        guard let path = (defaults.dictionary(forKey: "excludedApplicationPaths") as? [String: String])?[id] else { return nil }
        return URL(fileURLWithPath: path).deletingPathExtension().lastPathComponent
    }
    private let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    private let maxTextBytes = 1_000_000
    private let maxImageBytes = 20_000_000
    let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let sourceApp: () -> String?
    private let processingQueue = DispatchQueue(label: "com.rydool.clipboard-processing", qos: .utility)
    private var generation = 0
    private var pendingBytes = 0
    private var pendingJobs = 0
    private var store: HistoryStore?
    private var timer: Timer?
    private var imageProvider: HistoryTIFFProvider?
    private var lastChangeCount: Int
    private var maxBytes: Int { maxMegabytes * 1_000_000 }

    init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard,
         storeURL: URL? = nil, startTimer: Bool = true,
         sourceApp: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.sourceApp = sourceApp
        tracking = defaults.object(forKey: "clipboardTracking") as? Bool ?? true
        maxItems = defaults.object(forKey: "historyMaxItems") as? Int ?? 200
        maxMegabytes = defaults.object(forKey: "historyMaxMB") as? Int ?? 500
        excludedApps = defaults.string(forKey: "excludedBundleIDs") ?? ""
        lastChangeCount = pasteboard.changeCount
        do {
            let url: URL
            if let storeURL { url = storeURL }
            else {
                let root = try FileManager.default.url(for: .applicationSupportDirectory, in: .userDomainMask, appropriateFor: nil, create: true).appendingPathComponent("Rydool", isDirectory: true)
                url = root.appendingPathComponent("history.sqlite")
            }
            store = try HistoryStore(url: url)
            try reload()
        } catch { errorMessage = error.localizedDescription }
        if startTimer { timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        } }
    }

    func poll() {
        let current = pasteboard.changeCount
        guard current != lastChangeCount else { return }
        lastChangeCount = current
        guard tracking else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard ignoredTypes.isDisjoint(with: types), !types.contains("public.file-url") else { return }
        let source = sourceApp()
        if !excludedIDs.isEmpty && (source == nil || excludedIDs.contains(source!)) { return }
        for item in pasteboard.pasteboardItems ?? [] {
            let itemTypes = Set(item.types.map(\.rawValue))
            guard ignoredTypes.isDisjoint(with: itemTypes) else { return }
        }
        // Prefer images; metadata is checked before decoding, then the PNG output is bounded too.
        for type in [NSPasteboard.PasteboardType.png, .tiff, NSPasteboard.PasteboardType("public.jpeg"), NSPasteboard.PasteboardType("public.heic")] {
            guard types.contains(type.rawValue), let raw = pasteboard.data(forType: type) else { continue }
            guard raw.count <= maxImageBytes else { showTooLarge(); return }
            let fallback = pasteboard.string(forType: .string).flatMap { text -> Data? in
                guard !text.isEmpty else { return nil }
                let bytes = Data(text.utf8)
                return bytes.count <= maxTextBytes ? bytes : nil
            }
            enqueue(kind: .image, data: raw, source: source, fallback: fallback)
            return
        }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return }
        let data = Data(text.utf8)
        guard data.count <= maxTextBytes else { showTooLarge(); return }
        enqueue(kind: .text, data: data, source: source)
    }

    // Screenshot copies are recorded explicitly before focus changes, then their
    // pasteboard change count is consumed so polling cannot create a duplicate.
    func recordScreenshot(_ png: Data, source: String?, ownershipCount: Int) {
        lastChangeCount = ownershipCount
        guard tracking else { return }
        if !excludedIDs.isEmpty && (source == nil || excludedIDs.contains(source!)) { return }
        guard png.count <= maxImageBytes else { showTooLarge(); return }
        enqueue(kind: .image, data: png, source: source)
    }

    @discardableResult func copy(_ item: HistoryItem) -> Bool {
        let pb = pasteboard
        do {
            guard let data = try store?.payload(id: item.id) else { errorMessage = L("This item is no longer in history."); return false }
            let ownershipCount = pb.clearContents()
            let success: Bool
            if item.kind == .text {
                success = pb.setString(String(data: data, encoding: .utf8) ?? "", forType: .string)
                imageProvider = nil
            } else {
                let pasteboardItem = NSPasteboardItem()
                pasteboardItem.setData(data, forType: .png)
                let provider = HistoryTIFFProvider(png: data)
                pasteboardItem.setDataProvider(provider, forTypes: [.tiff])
                imageProvider = provider
                success = pb.writeObjects([pasteboardItem])
            }
            lastChangeCount = ownershipCount
            if !success { errorMessage = L("Couldn't copy this item to the clipboard."); return false }
            try store?.touch(id: item.id)
            try reload()
            return true
        } catch { errorMessage = error.localizedDescription; return false }
    }
    func togglePin(_ item: HistoryItem) {
        do { try store?.setPinned(!item.isPinned, id: item.id, maxItems: maxItems, maxBytes: maxBytes); try reload() }
        catch { errorMessage = error.localizedDescription }
    }
    func delete(_ item: HistoryItem) {
        do { try store?.delete(id: item.id); try reload() }
        catch { errorMessage = error.localizedDescription }
    }
    func clear() {
        generation &+= 1
        do { try store?.clear(); try reload() }
        catch { errorMessage = error.localizedDescription }
    }
    // Decode and encode images off the main thread. Jobs are scheduled in copy
    // order, and invalidated if monitoring is paused, exclusions change, or the
    // user clears history while processing is in flight.
    private func enqueue(kind: HistoryItem.Kind, data: Data, source: String?, fallback: Data? = nil) {
        let size = data.count + (fallback?.count ?? 0)
        guard pendingJobs < 8, size <= 100_000_000 - pendingBytes else {
            errorMessage = L("Clipboard is busy; the new item was not saved.")
            HUD.show(L("Couldn't save clipboard item"), symbol: "exclamationmark.triangle")
            return
        }
        pendingJobs += 1
        pendingBytes += size
        let ticket = generation
        processingQueue.async { [weak self] in
            let result = kind == .image ? ClipboardImageCodec.normalize(data) : .valid(data)
            DispatchQueue.main.async { [weak self] in
                guard let self else { return }
                self.pendingJobs -= 1
                self.pendingBytes -= size
                guard self.tracking, self.generation == ticket else { return }
                switch result {
                case .valid(let payload): self.record(kind: kind, data: payload, source: source)
                case .tooLarge: self.showTooLarge()
                case .invalid:
                    if let fallback { self.record(kind: .text, data: fallback, source: source) }
                }
            }
        }
    }

    #if DEBUG
    func waitForPendingWork() async {
        await withCheckedContinuation { continuation in
            processingQueue.async { DispatchQueue.main.async { continuation.resume() } }
        }
    }
    #endif

    private func record(kind: HistoryItem.Kind, data: Data, source: String?) {
        guard let store else { errorMessage = L("Couldn't open clipboard history."); return }
        do { try store.insert(kind: kind, data: data, source: source, maxItems: maxItems, maxBytes: maxBytes); try reload() }
        catch {
            errorMessage = error.localizedDescription
            HUD.show(L("Couldn't save clipboard history"), symbol: "exclamationmark.triangle")
        }
    }
    private func reload() throws { items = try store?.all() ?? [] }
    private func applyLimits() {
        do { try store?.enforceLimits(maxItems: maxItems, maxBytes: maxBytes); try reload() }
        catch { errorMessage = error.localizedDescription }
    }
    private func showTooLarge() {
        errorMessage = L("Clipboard item is too large to save in history.")
        HUD.show(L("Clipboard item is too large"), symbol: "exclamationmark.triangle")
    }
}

private final class HistoryTIFFProvider: NSObject, NSPasteboardItemDataProvider {
    private let png: Data
    init(png: Data) { self.png = png }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .tiff, let bitmap = NSBitmapImageRep(data: png), let data = bitmap.tiffRepresentation else { return }
        item.setData(data, forType: .tiff)
    }
}

private enum ClipboardImageCodec {
    enum Result { case valid(Data), tooLarge, invalid }
    static func normalize(_ data: Data) -> Result {
        let maxPixels = 100_000_000
        let maxBytes = 20_000_000
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0 else { return .invalid }
        guard width <= maxPixels / height else { return .tooLarge }
        guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return .invalid }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return .invalid }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return .invalid }
        guard output.length <= maxBytes else { return .tooLarge }
        return .valid(output as Data)
    }
}
